def artifacts() -> dict[Path, str]:
    def pretty(value: object) -> str:
        return json.dumps(value, ensure_ascii=False, indent=2) + "\n"

    result = {
        ROOT
        / "schemas"
        / "knowledge-v1"
        / f"{table}.schema.json": pretty(model.model_json_schema())
        for table, model in TABLE_MODELS.items()
    }
    result[ROOT / "sql" / "migrations" / "001_knowledge_contract_v1.sql"] = (
        render_migration()
    )
    result[ROOT / "docs" / "examples" / "knowledge-v1.json"] = pretty(example_bundle())
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check checked-in artifacts without writing",
    )
    args = parser.parse_args()
    stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Outdated artifacts:\n" + "\n".join(stale))
        return 1
    print(
        "Knowledge contract v1 artifacts " + ("verified" if args.check else "exported")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
