def bq_type(node: dict, definitions: dict) -> tuple[str, bool]:
    if "$ref" in node:
        return bq_type(definitions[node["$ref"].split("/")[-1]], definitions)
    if "anyOf" in node:
        choices = node["anyOf"]
        nullable = any(c.get("type") == "null" for c in choices)
        types = {bq_type(c, definitions)[0] for c in choices if c.get("type") != "null"}
        return (types.pop() if len(types) == 1 else "JSON"), nullable
    kind = node.get("type")
    if kind == "array":
        item_type, _ = bq_type(node["items"], definitions)
        return ("JSON" if item_type == "JSON" else f"ARRAY<{item_type}>"), False
    if kind == "string" and node.get("format") == "date-time":
        return "TIMESTAMP", False
    return {
        "string": "STRING",
        "integer": "INT64",
        "number": "FLOAT64",
        "boolean": "BOOL",
        "object": "JSON",
    }.get(kind, "JSON"), False


def render_migration() -> str:
    statements = [
        "-- Generated by scripts/export_knowledge_contract.py; do not edit by hand.",
        "-- Phase 1: additive schema only. No backfill, DML or automatic execution.",
        "-- Run existing sql/create_tables.sql first; substitute PROJECT_ID and DATASET.",
        "-- Uniqueness, references and enum/cross-field checks are application responsibilities.",
    ]
    for table, model in TABLE_MODELS.items():
        schema = model.model_json_schema()
        columns = []
        for name, prop in schema["properties"].items():
            kind, nullable = bq_type(prop, schema.get("$defs", {}))
            required = "" if nullable or kind.startswith("ARRAY<") else " NOT NULL"
            columns.append(f"  {name} {kind}{required}")
        partition, cluster = TABLE_OPTIONS[table]
        sql = (
            f"\nCREATE TABLE IF NOT EXISTS `${{PROJECT_ID}}.${{DATASET}}.{table}`\n(\n"
        )
        sql += ",\n".join(columns) + "\n)\n"
        if partition:
            sql += f"PARTITION BY DATE({partition})\n"
        sql += f"CLUSTER BY {cluster}\nOPTIONS (description = 'Knowledge contract v1: {model.__name__}');"
        statements.append(sql)
    return "\n".join(statements) + "\n"


